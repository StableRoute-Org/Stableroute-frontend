#!/usr/bin/env node
/**
 * check-staged-secrets.js
 * ----------------------------------------------------------------------------
 * Lightweight secret scanner used by the pre-commit hook and CI.
 *
 * Responsibilities:
 *   1. Reject staged files whose basenames match BLOCKED_FILENAME_PATTERNS
 *      (e.g. `.env`, `.env.local`, `id_rsa`, `*.pem`, `*.key`).
 *   2. Reject staged file content containing known-vendor credentials via
 *      PATTERN_DEFINITIONS (AWS, GitHub, Stripe, Slack, Google, OpenAI,
 *      Anthropic, private key blocks, JWT-excluding bearer headers, ...).
 *   3. Reject assignment-style lines whose value is a long, high-entropy
 *      string that is not part of a known-safe shape (SRI hashes, base64
 *      data URIs, embedded minified assets).
 *
 * Pure, dependency-free, CommonJS so it can be imported by Jest
 * (`scripts/__tests__/checkStagedSecrets.test.js`).
 *
 * Exit codes:
 *   0 — clean
 *   1 — at least one finding was reported
 *   2 — I/O / git error
 */

'use strict';

const path = require('path');

// ---------------------------------------------------------------------------
// Filename blocklist (matched on basename, not full path).
// ---------------------------------------------------------------------------

/**
 * Regexes matched against `path.basename(file)` to forbid staging entirely.
 *
 * Note: kept broad-but-conservative. The aim is to refuse any file that has a
 * non-trivial chance of being a real credential, not to auto-reject every
 * `.env.example`-style template because contributors need to be able to
 * `.gitignore` them locally. We therefore do NOT special-case `.env.example`.
 */
const BLOCKED_FILENAME_PATTERNS = [
  /^\.env$/i,
  /^\.env\..+$/i, // .env.local, .env.production, .env.test, etc.
  /^\.envrc$/i,
  /\.pem$/i,
  /\.key$/i,
  /\.p12$/i,
  /\.pfx$/i,
  /(^|\/)id_rsa$/i,
  /(^|\/)id_dsa$/i,
  /(^|\/)id_ed25519$/i,
  /(^|\/)id_ecdsa$/i,
];

/**
 * Files whose content we should NOT scan (they emit huge volumes of false
 * positives because they are large, autogenerated blobs).
 */
const SKIP_CONTENT_PATTERNS = [
  /package-lock\.json$/i,
  /yarn\.lock$/i,
  /pnpm-lock\.yaml$/i,
  /\.min\.js$/i,
  /\.min\.css$/i,
  /check-staged-secrets\.js$/i,
];

