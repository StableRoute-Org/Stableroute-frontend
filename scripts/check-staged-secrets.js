/**
 * Patterns whose presence on a line makes the heuristic entropy check
 * false-positive-prone (e.g. Subresource Integrity hashes, data: URLs,
 * minified asset SHA digests, comment markers). When ANY of these match
 * a line we skip high-entropy detection on that line entirely; vendor
 * patterns still apply.
 */
const SAFE_LINE_PATTERNS = [
  /\bdata:image\/[a-z]+;base64,/i,
  /\bsha(256|384|512)-[A-Za-z0-9+/=]{16,}\b/i,
  /^\s*\/\//, // JS/TS line comment
  /^\s*#/, // shell / yaml line comment
  /^\s*\*/,
];

/**
 * Inline disable marker. Mirrors `eslint-disable-next-line` semantics so
 * contributors have a familiar escape hatch. Allowed variants:
 *
 *   const TOKEN = '...'; // stableroute-disable-line secret-scan
 *   key: '<value>'        // stableroute-disable-next-line secret-scan
 */
const INLINE_DISABLE_PATTERN =
  /\bsta?bleroute-disable(?:-next-line|-line)?\s+secret-scan\b/i;

/**
 * Regex used by `scanTextContent` to detect a "next-line" disable carried
 * on the previous line. Mirrors ESLint's `eslint-disable-next-line`.
 */
const NEXT_LINE_DISABLE_RE =
  /\bsta?bleroute-disable-next-line\s+secret-scan\b/i;

// ---------------------------------------------------------------------------
// Pure helpers — independently unit-tested.
// ---------------------------------------------------------------------------

/**
 * Shannon entropy of `str` in bits/character. Returns 0 for empty strings.
 * Operates on the Unicode code-unit stream (sufficient for opaque tokens;
 * we are not doing cryptanalysis, just distinguishing random vs English).
 */
function calculateShannonEntropy(str) {
  if (!str || str.length === 0) return 0;

  const counts = Object.create(null);
  for (let i = 0; i < str.length; i += 1) {
    const ch = str[i];
    counts[ch] = (counts[ch] || 0) + 1;
  }

  let entropy = 0;
  const length = str.length;
  for (const ch in counts) {
    const p = counts[ch] / length;
    entropy -= p * Math.log2(p);
  }
  return entropy;
}

/**
 * True when `value` is long enough AND has enough entropy to look like
 * a credential rather than a human-meaningful token.
 */
function isHighEntropy(value, config) {
  if (!value || typeof value !== 'string') return false;
  if (value.length < config.minLength) return false;
  return calculateShannonEntropy(value) >= config.minEntropy;
}

/**
 * Pull the right-hand side of `key [:=] value` (quoted or bare) out of
 * a line. Returns null if the line isn't an assignment.
 *
 * Tolerant of:
 *   - bare and quoted RHS:  `KEY = abc`, `KEY="abc"`, `KEY='abc'`
 *   - trailing punctuation: `KEY = "abc";`  `KEY: 'abc',`
 *   - inline comments:      `KEY = abc # comment`
 *   - YAML / JSON keys:     `"key": "value"`, `key: value`
 *
 * Refuses lines that are clearly comments or lack an identifier on the LHS.
 */
function extractAssignmentValue(line) {
  if (typeof line !== 'string') return null;
  if (/^\s*\/\//.test(line)) return null;
  if (/^\s*#/.test(line)) return null;
  if (/^\s*\*/.test(line)) return null;

  // Find the first `=` or `:` outside quotes that is preceded by what
  // looks like an identifier. We use a tolerant scan rather than a single
  // giant regex so the value-extraction logic stays readable.
  let opIdx = -1;
  let inQuote = null;
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (inQuote) {
      if (ch === inQuote) inQuote = null;
      continue;
    }
    if (ch === '"' || ch === "'") {
      inQuote = ch;
      continue;
    }
    if (ch === '=' || ch === ':') {
      opIdx = i;
      break;
    }
  }
  if (opIdx === -1) return null;

  const lhs = line.slice(0, opIdx).trim().replace(/^["']|["']$/g, '');
  if (!/^[A-Za-z_][\w.\-]*$/.test(lhs)) return null;

  let rhs = line.slice(opIdx + 1).trim();
  rhs = rhs.replace(/\s+#.*$/, '');
  rhs = rhs.replace(/^["']+/, '').replace(/["']+$/, ''); // stableroute-disable-line secret-scan
  rhs = rhs.replace(/[;,}\]]+\s*$/, '').trim();
  return rhs.length > 0 ? rhs : null;
}

/**
 * Look up `path` in `fileContents` and return its string content. Used
 * by both staged (git) and working-tree (fs) flows.
 */
function readContent(file, fileContents) {
  if (!fileContents) return null;
  if (Object.prototype.hasOwnProperty.call(fileContents, file)) {
    return fileContents[file];
  }
  return null;
}

/**
 * Decide whether a filename is on the blocklist (matched against basename).
 */
function isBlockedFilename(file) {
  const base = path.basename(file);
  return BLOCKED_FILENAME_PATTERNS.some((re) => re.test(base));
}

/**
 * Decide whether the content of `file` should be skipped entirely.
 */
function shouldSkipContent(file) {
  const base = path.basename(file);
  return SKIP_CONTENT_PATTERNS.some((re) => re.test(base));
}

/**
 * Decide whether a line should bypass the high-entropy heuristic. Vendor
 * patterns still apply on safe lines; this is purely about avoiding
 * `SHA…` / `data:image/...` false positives.
 */
function isSafeLine(line) {
  return SAFE_LINE_PATTERNS.some((re) => re.test(line));
}

/**
 * Run all PATTERN_DEFINITIONS (and the entropy heuristic for assignment
 * lines) against a single line of source. Returns an array of matches.
 *
 * `options.skipCurrentLine` is set by `scanTextContent` when the preceding
 * line carried a `stableroute-disable-next-line secret-scan` marker.
 *
 * `options.env` is consulted so programmatic callers can honour
 * `STABLEROUTE_SKIP_SECRET_SCAN` in addition to flag-driven `--allow-skip`.
 */
function findSecretMatches(line, options) {
  const { patterns, entropyConfig, skipCurrentLine, env } = options;
  const matches = [];

  if (!line || typeof line !== 'string') return matches;

  if (env && env.STABLEROUTE_SKIP_SECRET_SCAN === '1') return matches;
  if (INLINE_DISABLE_PATTERN.test(line)) return matches;
  if (skipCurrentLine) return matches;

  const entropySuppressed = isSafeLine(line);
  const isAssignment = extractAssignmentValue(line) !== null;
  const assignmentValue = isAssignment ? extractAssignmentValue(line) : null;

  for (const def of patterns) {
    if (def.assignmentOnly && !isAssignment) continue;
    const m = line.match(def.regex);
    if (!m) continue;

    if (def.id === 'generic-secret-assignment') {
      const captured = m[1];
      if (!captured || !isHighEntropy(captured, entropyConfig)) continue;
    }

    matches.push({
      type: def.id,
      description: def.description,
      preview: redactPreview(m[0]),
      lineNumber: -1, // filled in by scanTextContent
    });
  }

  if (!entropySuppressed && isAssignment && assignmentValue) {
    if (isHighEntropy(assignmentValue, entropyConfig)) {
      matches.push({
        type: 'high-entropy-assignment',
        description: 'High-entropy value assigned to a sensitive-looking key',
        preview: redactPreview(assignmentValue),
        lineNumber: -1,
      });
    }
  }

  return matches;
}

/**
 * Render a string in a way that doesn't echo the whole secret to the logs.
 * Keeps the prefix/suffix so contributors can still recognise which token
 * matched, plus a short length-based fingerprint.
 */
function redactPreview(raw) {
  if (!raw || raw.length === 0) return '';
  if (raw.length <= 8) return `${raw[0]}***(${raw.length})`;
  return `${raw.slice(0, 4)}…${raw.slice(-4)} (len=${raw.length})`;
}

/**
 * Scan a single file's content. Returns:
 *   { path, skipped: boolean, matches: Array<{ type, description, preview, line, lineNumber }> }
 *
 * Tracks `stableroute-disable-next-line secret-scan` markers across lines
 * so a contributor can opt out a single line with a comment that's
 * physically attached to the previous line (mirrors `eslint-disable-next-line`).
 */
function scanTextContent(file, content, options) {
  const result = { path: file, skipped: false, matches: [] };
  if (content == null) return result;

  if (shouldSkipContent(file)) {
    result.skipped = true;
    return result;
  }

  const lines = String(content).split(/\r?\n/);
  let disableNext = false;

  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    const lineOptions = { ...options, skipCurrentLine: disableNext };
    const lineMatches = findSecretMatches(line, lineOptions);
    for (const m of lineMatches) {
      result.matches.push({ ...m, line, lineNumber: i + 1 });
    }
    disableNext = NEXT_LINE_DISABLE_RE.test(line);
  }
  return result;
}

// ---------------------------------------------------------------------------
// Orchestrator.
// ---------------------------------------------------------------------------

const DEFAULT_ENTROPY_CONFIG = Object.freeze({
  minLength: 20,
  minEntropy: 4.5,
});

/**
 * Default env source — overridable for tests.
 */
function defaultEnv() {
  return process.env || {};
}

/**
 * Pure entry point. `fileContents` is a `{ [path]: string }` map injected
 * by the caller — tests pass a literal, the CLI uses git or fs.
 *
 * `options.env` is consulted so the documented `STABLEROUTE_SKIP_SECRET_SCAN`
 * opt-out is honoured here too, not only in the CLI wrapper.
 *
 * Returns:
 *   {
 *     ok: boolean,
 *     skipped: boolean,             // true if allowSkip or env opt-out honoured
 *     blockedFilenames: string[],
 *     missingContents: string[],    // staged paths we couldn't read
 *     fileFindings: Array<{ path, skipped, matches }>,
 *     summary: { blocked: number, matches: number, filesScanned: number, missing: number }
 *   }
 */
function runCheck({
  stagedFiles,
  fileContents,
  patterns = PATTERN_DEFINITIONS,
  entropyConfig = DEFAULT_ENTROPY_CONFIG,
  allowSkip = false,
  env = defaultEnv(),
} = {}) {
  const skipEnv = env && env.STABLEROUTE_SKIP_SECRET_SCAN === '1';
  if (allowSkip || skipEnv) {
    return {
      ok: true,
      skipped: true,
      blockedFilenames: [],
      missingContents: [],
      fileFindings: [],
      summary: {
        blocked: 0,
        matches: 0,
        filesScanned: 0,
        missing: 0,
        skipReason: skipEnv ? 'env' : allowSkip ? 'flag' : null,
      },
    };
  }

  const files = Array.isArray(stagedFiles) ? stagedFiles : [];
  const blockedFilenames = files.filter(isBlockedFilename);
  const fileFindings = [];
  const missingContents = [];
  let matches = 0;
  let filesScanned = 0;

  for (const file of files) {
    if (isBlockedFilename(file)) continue;
    if (shouldSkipContent(file)) {
      fileFindings.push({ path: file, skipped: true, matches: [] });
      continue;
    }
    const content = readContent(file, fileContents);
    if (content == null) {
      // File is staged but we couldn't source its content (binary,
      // renamed, missing on disk for working-tree mode). Surface this so
      // operators can tell "scan OK" from "scan inconclusive".
      missingContents.push(file);
      fileFindings.push({ path: file, skipped: false, matches: [] });
      continue;
    }
    const finding = scanTextContent(file, content, {
      patterns,
      entropyConfig,
      env,
    });
    fileFindings.push(finding);
    if (!finding.skipped) filesScanned += 1;
    matches += finding.matches.length;
  }

  const ok = blockedFilenames.length === 0 && matches === 0;

  return {
    ok,
    skipped: false,
    blockedFilenames,
    missingContents,
    fileFindings,
    summary: {
      blocked: blockedFilenames.length,
      matches,
      filesScanned,
      missing: missingContents.length,
    },
  };
}

// ---------------------------------------------------------------------------
// Pretty-printer (used by the CLI but pure enough to test).
// ---------------------------------------------------------------------------

function formatReport(result, opts = {}) {
  const lines = [];
  const verbose = opts.verbose !== false;
  if (result.skipped) {
    const reason = result.summary && result.summary.skipReason
      ? ` (reason=${result.summary.skipReason})`
      : '';
    lines.push(`[secret-scan] SKIPPED${reason}`);
    return lines.join('\n');
  }

  if (verbose) lines.push('[secret-scan] scanning…');

  for (const f of result.fileFindings) {
    if (f.skipped) {
      lines.push(`  • ${f.path} — content scan skipped (lockfile/minified)`);
    }
  }

  if (result.missingContents && result.missingContents.length > 0) {
    for (const f of result.missingContents) {
      lines.push(`  ⚠ ${f} — staged but content unavailable (binary or unreadable)`);
    }
  }

  for (const name of result.blockedFilenames) {
    lines.push(`  ✖ ${name} — blocked filename (.env, .pem, id_rsa, …)`);
  }

  for (const f of result.fileFindings) {
    if (f.skipped) continue;
    for (const m of f.matches) {
      lines.push(
        `  ✖ ${f.path}:${m.lineNumber} — ${m.description} (type=${m.type}, preview=${m.preview})`
      );
    }
  }

  const { blocked, matches, filesScanned, missing } = result.summary;
  if (result.ok) {
    const tail = missing > 0 ? `, ${missing} unreadable` : '';
    lines.push(
      `[secret-scan] OK — ${filesScanned} file(s) scanned, no findings${tail}.`
    );
  } else {
    lines.push(
      `[secret-scan] FAIL — ${blocked} blocked filename(s), ${matches} content match(es).`
    );
  }
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// Default I/O adapters (production).
// ---------------------------------------------------------------------------

// Module-level caches for the default I/O adapters. Node's `require` is
// itself cached, so this is a no-op in steady state — the cache exists to
// give a single, stable reference for callers that want to reason about
// "is defaultFsAdapter the same module across invocations?" and to avoid
// any future foot-gun if a test wants to assert no default adapter ran.
// Tests that inject their own fsAdapter/gitRunner bypass this state entirely.
let _cachedFs;
// eslint-disable-next-line no-unused-vars
let _cachedCp;

function defaultGitRunner(cmd, args, cwd) {
  // eslint-disable-next-line global-require
  if (!_cachedCp) _cachedCp = require('child_process');
  const { spawnSync } = _cachedCp;
  const result = spawnSync('git', [cmd, ...args], {
    cwd: cwd || process.cwd(),
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(
      `git ${cmd} ${args.join(' ')} failed: ${(result.stderr || '').trim() || `exit ${result.status}`}`
    );
  }
  return result.stdout || '';
}

function defaultFsAdapter() {
  // Memoize the require so test-time injection of a stateful adapter
  // never produces two separate fs modules.
  if (!_cachedFs) _cachedFs = require('fs');
  return _cachedFs;
}

// ---------------------------------------------------------------------------
// CLI helpers — each takes an injected runner/fs so tests can pass mocks.
// ---------------------------------------------------------------------------

function getStagedFiles(cwd, runner = defaultGitRunner) {
  const out = runner(
    'diff',
    ['--cached', '--name-only', '--diff-filter=ACMR'],
    cwd
  );
  return out
    .split('\n')
    .map((s) => s.trim())
    .filter(Boolean);
}

function getStagedFileContent(file, cwd, runner = defaultGitRunner) {
  return runner('show', [`:${file}`], cwd);
}

function getWorkingTreeFiles(cwd, fsDep = defaultFsAdapter()) {
  const fs = fsDep;
  const root = cwd || process.cwd();
  const out = new Set();
  const skipDirs = new Set([
    'node_modules',
    '.next',
    'out',
    'coverage',
    '.git',
    '.lighthouseci',
    'dist',
    'build',
  ]);
  const skipContentRe = SKIP_CONTENT_PATTERNS;

  function walk(dir) {
    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch (_e) {
      return;
    }
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (skipDirs.has(entry.name)) continue;
        walk(full);
      } else if (entry.isFile()) {
        const rel = path.relative(root, full);
        if (skipContentRe.some((re) => re.test(entry.name))) {
          out.add(rel);
          continue;
        }
        let stat;
        try {
          stat = fs.statSync(full);
        } catch (_e) {
          continue;
        }
        if (stat.size > 1024 * 1024) continue;
        out.add(rel);
      }
    }
  }

  walk(root);
  return Array.from(out).sort();
}

function readWorkingTreeFiles(files, cwd, fsDep = defaultFsAdapter()) {
  const fs = fsDep;
  const root = cwd || process.cwd();
  const map = {};
  for (const f of files) {
    const full = path.join(root, f);
    try {
      // Heuristic: peek the first 4 bytes. If the leading byte is NUL,
      // the file is almost certainly binary (UTF-8 text never starts with
      // 0x00) so we skip it without spending more I/O.
      const fd = fs.openSync(full, 'r');
      const buf = Buffer.alloc(4);
      fs.readSync(fd, buf, 0, 4, 0);
      fs.closeSync(fd);
      if (buf[0] === 0) continue;
      map[f] = fs.readFileSync(full, 'utf8');
    } catch (_e) {
      // ignore — file may have been deleted between walk and read
    }
  }
  return map;
}

function getPrDiffFiles(cwd, baseRef, runner = defaultGitRunner) {
  const target = baseRef || 'origin/main';

  try {
    const threeDot = runner(
      'diff',
      ['--name-only', '--diff-filter=ACMR', `${target}...HEAD`],
      cwd
    )
      .split('\n')
      .map((s) => s.trim())
      .filter(Boolean);
    if (threeDot.length > 0) return threeDot;
  } catch (_err) {
    // Merge base not reachable (e.g. shallow clone, missing origin/main)
  }

  // Fallback when no merge-base is reachable (e.g. shallow clone, fork):
  // two-dot diff is conservative — entire tree relative to base.
  try {
    const twoDot = runner(
      'diff',
      ['--name-only', '--diff-filter=ACMR', target, 'HEAD'],
      cwd
    )
      .split('\n')
      .map((s) => s.trim())
      .filter(Boolean);
    if (twoDot.length > 0) return twoDot;
  } catch (_err) {
    // Fallback to comparing HEAD~1 if target ref does not exist locally
  }

  try {
    const headPrev = runner(
      'diff',
      ['--name-only', '--diff-filter=ACMR', 'HEAD~1', 'HEAD'],
      cwd
    )
      .split('\n')
      .map((s) => s.trim())
      .filter(Boolean);
    return headPrev;
  } catch (_err) {
    return [];
  }
}

function getPrDiffContents(files, cwd, fsDep = defaultFsAdapter()) {
  return readWorkingTreeFiles(files, cwd, fsDep);
}

// ---------------------------------------------------------------------------
// Argv + help + CLI orchestration.
// ---------------------------------------------------------------------------

function parseArgs(argv) {
  // Tiny parser, no deps. Supported flags:
  //   --scope=staged         (default; uses `git diff --cached`)
  //   --scope=working-tree   (scans cwd, for local dry-runs)
  //   --scope=pr-diff        (scans `origin/main...HEAD` diff, for CI)
  //   --base-ref=<ref>       (override base ref for --scope=pr-diff)
  //   --allow-skip           (treat as a no-op success; used to verify wiring)
  const out = { scope: 'staged', baseRef: 'origin/main', allowSkip: false };
  for (const arg of argv.slice(2)) {
    if (arg.startsWith('--scope=')) {
      out.scope = arg.slice('--scope='.length);
    } else if (arg.startsWith('--base-ref=')) {
      out.baseRef = arg.slice('--base-ref='.length);
    } else if (arg === '--allow-skip') {
      out.allowSkip = true;
    } else if (arg === '--help' || arg === '-h') {
      out.help = true;
    } else {
      out.unknown = arg;
    }
  }
  return out;
}

function printHelp() {
  return [
    'Usage: node scripts/check-staged-secrets.js [options]',
    '',
    'Options:',
    '  --scope=staged         Scan staged files (default).',
    '  --scope=working-tree   Scan the entire working tree (local dry-run).',
    '  --scope=pr-diff        Scan the diff vs --base-ref (CI mode).',
    '  --base-ref=<ref>       Base ref for --scope=pr-diff (default: origin/main).',
    '  --allow-skip           Exit 0 without scanning (verify install only).',
    '  -h, --help             Show this help.',
    '',
    'Environment variables:',
    '  STABLEROUTE_SKIP_SECRET_SCAN=1  Bypass the scanner entirely (CI opt-out).',
    '  STABLEROUTE_SKIP_PRECOMMIT=1    Bypass the whole pre-commit hook.',
    '',
  ].join('\n');
}

// ---------------------------------------------------------------------------
// Main CLI. `runMain(args, deps)` is the testable entry point — `main(...)`
// is a thin wrapper that binds real I/O and exits the process.
// ---------------------------------------------------------------------------

function runMain(args, deps = {}) {
  const {
    gitRunner = defaultGitRunner,
    fsAdapter = defaultFsAdapter,
    env = process.env || {},
    stdout = process.stdout,
    stderr = process.stderr,
    exitFn = (code) => process.exit(code),
    cwd = process.cwd(),
  } = deps;

  if (args.help) {
    stdout.write(printHelp());
    return 0;
  }
  if (args.unknown) {
    stderr.write(`Unknown flag: ${args.unknown}\n`);
    stdout.write(printHelp());
    return 2;
  }

  // Hyper-broad opt-out handled by runCheck via `env`.
  // For the CLI we additionally treat this as a "no-op success" exit.
  if (env.STABLEROUTE_SKIP_PRECOMMIT === '1') {
    stdout.write(
      '[secret-scan] SKIPPED — STABLEROUTE_SKIP_PRECOMMIT=1\n'
    );
    return 0;
  }

  let stagedFiles;
  let fileContents;

  try {
    if (args.scope === 'staged') {
      stagedFiles = getStagedFiles(cwd, gitRunner);
      fileContents = Object.create(null);
      for (const f of stagedFiles) {
        if (shouldSkipContent(f)) continue;
        if (isBlockedFilename(f)) continue;
        try {
          fileContents[f] = getStagedFileContent(f, cwd, gitRunner);
        } catch (_e) {
          // File may be binary or renamed; surface as missing in runCheck.
        }
      }
    } else if (args.scope === 'working-tree') {
      const fsDep = typeof fsAdapter === 'function' ? fsAdapter() : fsAdapter;
      stagedFiles = getWorkingTreeFiles(cwd, fsDep);
      fileContents = readWorkingTreeFiles(stagedFiles, cwd, fsDep);
    } else if (args.scope === 'pr-diff') {
      const fsDep = typeof fsAdapter === 'function' ? fsAdapter() : fsAdapter;
      stagedFiles = getPrDiffFiles(cwd, args.baseRef, gitRunner);
      fileContents = getPrDiffContents(stagedFiles, cwd, fsDep);
    } else {
      stderr.write(`Unknown --scope value: ${args.scope}\n`);
      return 2;
    }
  } catch (e) {
    stderr.write(`[secret-scan] ERROR: ${e.message}\n`);
    return 2;
  }

  const result = runCheck({
    stagedFiles,
    fileContents,
    allowSkip: args.allowSkip,
    env,
  });
  stdout.write(formatReport(result) + '\n');
  if (!result.ok) {
    exitFn(1);
    return 1;
  }
  return 0;
}

function main(argv) {
  const args = parseArgs(argv || process.argv);
  const rc = runMain(args);
  if (rc !== 0) process.exit(rc);
  return rc;
}

